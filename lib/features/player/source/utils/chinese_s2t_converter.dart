  static final Map<int, String> _s2tMap = () {
    final map = <int, String>{};
    final len = _simplified.length;
    for (var i = 0; i < len; i++) {
      map[_simplified.codeUnitAt(i)] = _traditional[i];
    }
    for (final entry in _extraAnimeMap.entries) {
      map[entry.key.codeUnitAt(0)] = entry.value;
    }
    return map;
  }();

  /// 简体中文转换为繁体中文 (逐字符极速转换)
  static String convert(String input) {
    if (input.isEmpty) return input;
    final buffer = StringBuffer();
    for (var i = 0; i < input.length; i++) {
      final code = input.codeUnitAt(i);
      final mapped = _s2tMap[code];
      if (mapped != null) {
        buffer.write(mapped);
      } else {
        buffer.writeCharCode(code);
      }
    }
    return buffer.toString();
  }

  /// 生成针对 Anime1 等繁体源的候选关键词变体
  /// 1:1 对齐 animaku keywordVariantsZh
  static List<String> keywordVariantsZh(String keyword) {
    final raw = keyword.replaceAll(RegExp(r'\s+'), ' ').trim();
    if (raw.isEmpty) return const [];
    final trad = convert(raw).trim();
    final out = <String>[];

    void push(String s) {
      if (s.isNotEmpty && !out.contains(s)) {
        out.add(s);
      }
    }

    // 繁体最优先
    push(trad);
    push(raw);

    // 去除季数后缀（第二季 / 第2季 / S2）匹配大系列主页面
    final stripped = trad
        .replaceAll(RegExp(r'\s*第\s*[一二三四五六七八九十\d]+\s*[季期部]\s*'), '')
        .replaceAll(RegExp(r'\s*S\d+\s*', caseSensitive: false), '')
        .trim();
    if (stripped.isNotEmpty && stripped != trad) {
      push(stripped);
    }

    return out;
  }
